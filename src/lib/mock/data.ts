export function mockCalculateDriveTime(originId: string, destinationId: string): DriveTimeResult {
  const origin = MOCK_AMENITIES.find((a) => a.id === originId);
  const dest = MOCK_AMENITIES.find((a) => a.id === destinationId);
  if (!origin || !dest) {
    return { originId, destinationId, duration: 0, distance: 0, durationText: 'Unknown', distanceText: 'Unknown' };
  }
  const R = 6371000;
  const dLat = ((dest.lat - origin.lat) * Math.PI) / 180;
  const dLng = ((dest.lng - origin.lng) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((origin.lat * Math.PI) / 180) * Math.cos((dest.lat * Math.PI) / 180) * Math.sin(dLng / 2) ** 2;
  const distance = R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const duration = (distance / (35000 / 3600)) * (1 + Math.random() * 0.25);
  const minutes = Math.round(duration / 60);
  const miles = (distance / 1609).toFixed(1);
  return {
    originId, destinationId,
    duration: Math.round(duration), distance: Math.round(distance),
    durationText: minutes < 60 ? `${minutes} min` : `${Math.floor(minutes / 60)}h ${minutes % 60}m`,
    distanceText: `${miles} mi`,
  };
}